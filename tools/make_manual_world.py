"""Generate the World Studio beginner's guide as a Word (.docx) document.

Run::

    python tools/make_manual_world.py

Output: ``docs/WorldStudio_新手引导.docx``
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

from make_manual import _cjk, _setup, bullets, h1, h2, numbers, p, table

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "WorldStudio_新手引导.docx"


def build() -> Document:
    doc = Document()
    _setup(doc)

    # -- cover --------------------------------------------------------------
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    trun = title.add_run("World Studio 新手引导")
    trun.bold = True
    trun.font.size = Pt(28)
    _cjk(trun.font)
    sub = doc.add_paragraph()
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
    srun = sub.add_run("世界观工坊 · 从只言片语到一份世界观文档")
    srun.font.size = Pt(13)
    srun.font.color.rgb = RGBColor.from_string("666666")
    _cjk(srun.font)
    ver = doc.add_paragraph()
    ver.alignment = WD_ALIGN_PARAGRAPH.CENTER
    vrun = ver.add_run("适用版本 v2.27　·　Novel Jazz Engine")
    vrun.font.size = Pt(11)
    vrun.font.color.rgb = RGBColor.from_string("999999")
    _cjk(vrun.font)
    doc.add_paragraph()

    # -- TOC ----------------------------------------------------------------
    h1(doc, "目录")
    bullets(doc, [
        "一、这是什么（60 秒了解）",
        "二、安装与启动",
        "三、5 分钟快速上手",
        "四、设定嫁接：改造已有世界观",
        "五、设定状态、依赖与一致性",
        "六、目录与文件",
        "七、命令行速查",
        "八、接入真实模型",
        "九、常见问题（FAQ）",
    ])

    # -- 1 ------------------------------------------------------------------
    h1(doc, "一、这是什么（60 秒了解）")
    p(doc, "World Studio（世界观工坊）是 JazzWriter 里与“小说编排”并列的一个**独立模块**："
           "它有自己的启动入口、自己的窗口、自己的数据目录（worlds/），专门帮你从一小段灵感出发，"
           "长出一个世界；也能导入已有设定进行改造。")
    p(doc, "它最终产出一份 Markdown 文档 world.md —— 一份结构化、带来源、带状态、可继续打磨的世界观。")
    p(doc, "与一般“输入关键词→输出一大段设定”的工具不同，这里有两件事是刻意设计的：")
    bullets(doc, [
        "先发散、再收敛：同一个灵感会被解释成多个**底层逻辑不同**的世界原型，由你来选。",
        "把世界当假设：每条设定都有**状态**（已确认 / 候选 / 未决 / 有意保留的矛盾）、**依据**和**来源**，"
        "系统只提示冲突、不擅自修改，裁决权始终在你手里。",
    ])

    # -- 2 ------------------------------------------------------------------
    h1(doc, "二、安装与启动")
    p(doc, "前提：已安装 Python（3.9+）。图形界面只用标准库 Tkinter，无需额外安装。")
    h2(doc, "方式一：双击启动（最省事）")
    p(doc, "双击项目根目录下的 WorldStudio.bat，即可打开 World Studio 窗口。")
    h2(doc, "方式二：命令行")
    p(doc, "python world_studio_gui.py　（图形界面）")
    p(doc, "python world_studio.py --help　（命令行）")
    p(doc, "说明：默认使用离线 mock 模型，无需任何 API Key 即可跑通全流程"
           "（内容偏骨架化，但结构、依据、状态、导出一应俱全）。接入真实模型见第八章。")

    # -- 3 ------------------------------------------------------------------
    h1(doc, "三、5 分钟快速上手")
    p(doc, "打开 World Studio 后，按下面 6 步即可得到一份世界观文档。")
    h2(doc, "第 1 步：写下一句灵感")
    p(doc, "在最上方的“灵感种子”里写一句话即可，例如：")
    p(doc, "每个人死后都会留下一段从未说出口的记忆，但只有建筑能听见。")
    h2(doc, "第 2 步：发散")
    p(doc, "点「发散」。左侧会出现世界原型（**默认 4 个**，可用 --count 3–6 调整）。"
           "选中任意一个，右侧会列出它在**五个维度**上的不同："
           "**规则机制 / 权力结构 / 知识分配 / 人物困境 / 时间动力**，并显示差异度。"
           "若两个原型“标签不同但机制重复”，会标 ⚠。")
    p(doc, "发散后会自动保存到 worlds/<名称>/。")
    h2(doc, "第 3 步：选一个原型并生长")
    p(doc, "在左侧选中一个原型，点「选择并生长」。系统先由核心规则推出**结构属性**"
           "（可观测性 / 稀缺性 / 执行方式 / 代价 / 可变性，每条都带证据与把握度；"
           "无法判断时标“未知”并生成待确认问题），再据此推导出 社会后果 / 知识与认知 / 制度与权力 / "
           "历史动力 / 地理与空间 / 冲突与人物 / 意象与母题。")
    h2(doc, "第 4 步：查看与编辑")
    p(doc, "右侧就是 world.md 的实时内容。下方“设定条目”列表里选中任意一条，"
           "可把它标为「已确认 / 候选 / 未决 / 矛盾」，或「锁定」。"
           "在左下“编辑选中条目”里可以修改条目的**名称 / 内容 / 依据**——"
           "修改会**保留 id、来源与依赖关系**；若该条目已锁定或已确认，会先请你确认。"
           "**如果修改的是核心规则，系统会列出需要复核的下游候选**，不会静默覆盖。")
    p(doc, "锁定后如果条目被再次生长，已确认 / 已锁定的内容不会被改写。")
    h2(doc, "第 5 步：一致性检查")
    p(doc, "点「一致性检查」，查看疑似冲突（含依据与把握度）。注意：离线模式下系统会声明"
           "“不做语义判断”，所以“未发现冲突”不等于“与核心规则一致”。")
    h2(doc, "第 6 步：继续 / 导出")
    p(doc, "world.md 已写入 worlds/<名称>/world.md，也可点「另存副本」。"
           "下次想接着做：在上方「已有世界观」下拉里选择它，点「打开」——"
           "种子与原型列表会一并恢复，可直接继续选择与生长。")

    # -- 4 ------------------------------------------------------------------
    h1(doc, "四、设定嫁接：改造已有世界观")
    p(doc, "在左侧「设定嫁接」里选一种操作，点「导入设定文件并变形」，选择一份已有设定文档"
           "（.txt / .md）。系统先抽取**抽象骨架**（规则 / 主题 / 权力 / 历史 / 美学），"
           "再按操作生成**结构化变形计划**，据此产出新的核心规则与后果链。")
    table(doc, ["变形操作", "目标"], [
        ["深度变形", "保留少量核心规则，重新推导社会、历史与生活方式"],
        ["主题移植", "保留主题矛盾，改换时代、制度与技术条件"],
        ["世界交叉", "从两个设定中选择可兼容的规则，再处理冲突（需第二份材料）"],
        ["边缘扩展", "保留原世界底层逻辑，创造此前未重点描写的区域或时代"],
        ["反转前提", "改变一条关键假设，观察整个世界的连锁变化"],
    ])
    bullets(doc, [
        "默认**派生新世界**：源世界的文件不会被改动，新结果保存到新的目录名下。",
        "「世界交叉」需要**第二份材料**：GUI 会再让你选一个文件；命令行要加 --second <文件>，否则报错。",
        "文档里会写清 继承 / 删除 / 修改 / 新增 / 下游影响，以及来源与规则冲突；新增规则标为“候选”。",
        "嫁接以抽象规则与主题为材料，不复制原作的文字、人物与独特表达。",
    ])

    # -- 5 ------------------------------------------------------------------
    h1(doc, "五、设定状态、依赖与一致性")
    h2(doc, "四种状态")
    bullets(doc, [
        "已确认 confirmed：你认可的事实。",
        "候选 candidate：模型/推导提出的可能，尚未确认。",
        "未决 open：还没决定的问题。",
        "有意保留的矛盾 contradiction：刻意留下的张力（神秘、宗教、不可靠叙述可以来自这里）。",
    ])
    h2(doc, "依赖溯源")
    p(doc, "条目不是“都挂在核心规则下”，而是 规则 → 后果 → 制度/历史 → 地理/冲突 的链。"
           "因此可以反查“若修改某条规则，会牵连哪些候选设定”：命令行 world_studio.py impact <目录名> rule-1。")
    h2(doc, "一致性提示（只提示，不自动修正）")
    bullets(doc, [
        "合并同类重复；检查跨类别疑似冲突；专项检查“核心规则 ↔ 下游条目”。",
        "每条提示都带**依据**与**把握度**，启发式会漏报/误报，请自行裁决。",
        "接入真实模型时可加做语义审阅，结果会明确标注“需人工确认”。",
        "离线模式会声明“不做语义判断”：未发现冲突 ≠ 与核心规则一致。",
    ])
    h2(doc, "编辑与可靠性")
    bullets(doc, [
        "结构化编辑：改名称/内容/依据/状态，保留 id/来源/依赖；锁定或已确认的条目需确认；"
        "改核心规则会列出需复核的下游候选（GUI 表单或 CLI edit）。",
        "嫁接计划会作为明确约束进入模型生成提示，生成后校验是否满足，不满足则回退离线推导。",
        "模型 JSON 严格校验（最低类别覆盖、id 唯一、依赖引用有效、无环），不合格会记录原因并回退。",
        "保存采用原子写入（临时文件 + 原子替换），并保留上一版 .bak 备份。",
    ])

    # -- 6 ------------------------------------------------------------------
    h1(doc, "六、目录与文件")
    p(doc, "每个世界独立存放于 worlds/<名称>/：")
    bullets(doc, [
        "world.md　面向阅读与分享的结构化世界观文档（最终产物）。",
        "world.json　机器可读，用于下次打开继续编辑。",
        "worlds/ 只保存在本地，不会提交到代码仓库。",
    ])

    # -- 7 ------------------------------------------------------------------
    h1(doc, "七、命令行速查")
    table(doc, ["命令", "作用"], [
        ["spark \"一句话\"", "发散出多个世界原型"],
        ["spark \"一句话\" --pick 名称", "发散→选择→生长→导出，一步完成"],
        ["pick <目录名> idea-2", "稍后回到该项目，选第二个原型"],
        ["grow <目录名> [--pick 名称]", "生长并导出（未选原型会报错，不静默选第一条）"],
        ["graft <文件> --op 反转前提", "导入设定并变形（派生新世界）"],
        ["graft a.txt --op 世界交叉 --second b.txt", "世界交叉（必须有第二份材料）"],
        ["check <目录名>", "一致性提示（含依据/把握度/离线声明）"],
        ["show <目录名> --entries", "列出全部条目（[状态] id｜类别｜名称＋锁定）"],
        ["state <目录名> consequence-1 confirmed", "设置条目状态"],
        ["lock <目录名> rule-1 [--off]", "锁定 / 解锁条目"],
        ["edit <目录名> rule-1 --statement \"…\" [--yes]", "编辑条目（保留 id/来源/依赖；锁定或已确认需 --yes）"],
        ["impact <目录名> rule-1", "修改该条目会牵连哪些设定"],
        ["state <目录名> consequence-1 confirmed", "设置条目状态"],
        ["show <目录名> / list", "查看状态 / 列出本地世界观"],
    ])
    p(doc, "所有命令前可加 --out <目录> 指定世界观数据根目录（默认 worlds/）。")

    # -- 8 ------------------------------------------------------------------
    h1(doc, "八、接入真实模型")
    p(doc, "默认 mock 只用于离线演示。要获得真正的创意与文笔，请接入真实模型（二者兼容）。")
    h2(doc, "方式一：opencode（复用你已连接的模型）")
    numbers(doc, [
        "另开终端运行：opencode serve --port 4096",
        "运行：python world_studio_gui.py（或 world_studio.py），把顶部“模型”选为 opencode。",
    ])
    h2(doc, "方式二：OpenAI 兼容端点（OpenAI / DeepSeek / Qwen …）")
    p(doc, '$env:OPENAI_API_KEY = "你的key"')
    p(doc, '$env:NJE_BASE_URL = "https://api.deepseek.com/v1"')
    p(doc, '$env:NJE_MODEL = "deepseek-chat"')
    p(doc, "然后把“模型”选为 openai。")
    p(doc, "注意：world_studio.py 的 --provider 只决定“用哪个模型”，与小说编排共用同一套配置。"
           "若模型返回的 JSON 字段缺失或类别非法，系统会忽略并回退到离线推导，并在文档中给出提示。")

    # -- 9 ------------------------------------------------------------------
    h1(doc, "九、常见问题（FAQ）")
    table(doc, ["问题", "说明"], [
        ["导出到哪里？", "worlds/<名称>/world.md；也可在界面里「另存副本」。"],
        ["能否只发散、不生长？", "可以。点「发散」即已保存，之后可随时「打开」继续选原型。"],
        ["生长会覆盖我确认的内容吗？", "不会。已锁定 / 已确认的条目在再次生长时不会被改写。"],
        ["嫁接会覆盖原世界吗？", "不会。默认派生新世界，源世界保持原样。"],
        ["为什么很多条目标“候选”？", "这是刻意的：只有你确认后才成为事实，避免把猜想当既定设定。"],
        ["为什么清单里说“未发现冲突”仍要小心？", "离线检查是启发式的，不看语义；接入真实模型可加做语义审阅。"],
        ["能直接变成小说项目吗？", "当前以“输出一份 world.md”为目标；把它作为写作参考使用即可。"],
    ])

    return doc


def main() -> int:
    doc = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(OUT))
    print(f"written: {OUT}  ({len(doc.paragraphs)} paragraphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
